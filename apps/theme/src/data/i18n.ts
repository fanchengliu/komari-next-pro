export function translate(text: string, locale: string) {
  if (locale === "zh-CN") return text;
  const dictionary: Record<string, string> | undefined =
    locale === "zh-TW"
      ? zhTW
      : locale === "ja"
        ? ja
        : locale === "ko"
          ? ko
          : undefined;
  if (dictionary?.[text]) return dictionary[text];
  if (/^[-\d.]+天$/.test(text))
    return text.replace(
      "天",
      locale === "ja"
        ? "日"
        : locale === "ko"
          ? "일"
          : locale === "en"
            ? "d"
            : "天",
    );
  return (
    enV22[text] ??
    enV21[text] ??
    enV2[text] ??
    en[text] ??
    (/^[-\d.]+天$/.test(text) ? text.replace("天", "d") : text)
  );
}
export function useTranslate() {
  const locale = useUI((s) => s.preferences.locale ?? s.siteLocale);
  return (text: string) => translate(text, locale);
}
